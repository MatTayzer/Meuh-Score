// Enlever les accents d'un prénom
String _withoutAccents(String name) {
  const accents = {
    'à': 'a',
    'â': 'a',
    'ä': 'a',
    'á': 'a',
    'ã': 'a',
    'é': 'e',
    'è': 'e',
    'ê': 'e',
    'ë': 'e',
    'î': 'i',
    'ï': 'i',
    'í': 'i',
    'ô': 'o',
    'ö': 'o',
    'ó': 'o',
    'õ': 'o',
    'ù': 'u',
    'û': 'u',
    'ü': 'u',
    'ú': 'u',
    'ç': 'c',
    'ÿ': 'y',
    'ñ': 'n',
    'æ': 'ae',
    'œ': 'oe',
  };
  return name.split('').map((letter) => accents[letter] ?? letter).join();
}

// Choisi un avatar au hasard selon le sexe
String playerAvatar(String name) {
  final cleanName = name.toLowerCase().trim();

  if (cleanName == 'gaspar') {
    return AppAssets.gasparAvatar;
  }

  final images = _girlNames.contains(_withoutAccents(cleanName))
      ? AppAssets.playerGirls
      : AppAssets.playerBoys;

  final seed = cleanName.codeUnits.fold(0, (sum, code) => sum + code);
  return images[seed % images.length];
}
